"""
aot-mkshim.py -- write the shim a conversion needs, from the imports it has.

The shim is the platform the converted libraries bind to: whatever Android's runtime would
have provided. Hand-written behaviour lives in bionic-shim.c; everything else -- the
`__*_chk` fortify wrappers, the stdio globals bionic exposes, the NDK's interface ids --
is mechanical, and is generated here from the import list.

  aot-mkshim.py <lib/arm64-v8a/*.so ...> -o build/shim-generated.c [--exclude name ...]

A symbol that libSystem already provides must not be defined: the linker would call that a
duplicate, and `aot-mkshim.py --prune` turns those errors back into an exclusion list.
"""
import argparse
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from aotlib import Elf, sdk_for_target

# Symbols that are data, not functions. Defining one of these as a function would compile
# and then fault at run time on the caller's side, so they are declared as objects.
DATA_HINTS = ("__sF", "__serr", "__sidx", "__sout", "__sin_", "environ", "program_invocation",
              "tzname", "daylight", "timezone", "optarg", "optind", "opterr", "optopt")

PROLOGUE = """/* SPDX-License-Identifier: GPL-2.0-or-later */
/* generated by aot-mkshim.py -- do not edit; see bionic-shim.c for the hand-written part */
#include <stdio.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

/* The guest's names are C names, so these have C linkage whatever driver compiles this file:
 * clang++ would otherwise mangle the call to the hand-written half and the link would fail
 * with a symbol the file itself defines. */
#ifdef __cplusplus
extern "C" {
#endif

/* The hand-written half's own way of printing. The shim's fprintf is one of the guest's
 * entry points and takes its arguments the Android way, so the shim cannot use it for its
 * own text: that would read the arguments out of the wrong place. */
extern void husk_shim_logf(const char *fmt, ...);

static void shim_gap(const char *name)
{
    static __thread const char *reported;
    if (name == reported)
        return;
    reported = name;
    husk_shim_logf("bionic-shim: %s is a placeholder\\n", name);
}

/* The bridge to the hand-written part: the translation layer's implementations, which are
 * the same ones the ELF loader binds an import to when it maps the guest. */
extern void *husk_shim_host_impl(const char *name);
"""

EPILOGUE = """
#ifdef __cplusplus
}
#endif
"""

# A forwarder is declared with the argument registers and no types worth knowing. On
# AArch64 the integer and pointer arguments are x0-x7 and the floating-point ones are
# d0-d7, so a forwarder that names all sixteen and passes them on untouched delivers
# every argument correctly whatever its real type is -- including a double, which never
# entered x0 to begin with, and which a forwarder that named only x0-x7 would have
# dropped. That is what makes a generated forwarder correct without the headers for the
# library: OpenGL ES is not declared anywhere on the platform, and OpenSL ES is declared
# only in the NDK. There is no name mangling to get wrong either, since the Mach-O label
# is spelled out.
#
# The integer registers are not the whole story: AArch64 passes the ninth integer or
# pointer argument on the stack. A forwarder that names only x0-x7 therefore drops it,
# and the host implementation reads whatever the forwarder's own frame happens to hold
# there -- measured as glTexSubImage2D's pixels pointer arriving as 0x40000, crashing
# AGX. Naming sixteen integer arguments puts the guest's stack arguments into the
# forwarder's parameter list, so its call to the host implementation passes them on.
# OpenGL ES's longest imports (glTexImage3D, glTexSubImage3D) use ten.
FWD_N_INT = 16
FWD_N_DBL = 8
FWD_SIG = ", ".join(["unsigned long"] * FWD_N_INT + ["double"] * FWD_N_DBL)
FWD_PARAMS = ", ".join([f"unsigned long a{i}" for i in range(FWD_N_INT)] +
                       [f"double d{i}" for i in range(FWD_N_DBL)])
FWD_ARGS = ", ".join([f"a{i}" for i in range(FWD_N_INT)] +
                     [f"d{i}" for i in range(FWD_N_DBL)])
FWD_TYPEDEF = "typedef unsigned long aot_fwd_fn(%s);" % FWD_SIG
FWD_CAST = "aot_fwd_fn *"

FORWARDER_NOTE = """
/* Forwarded names. Each is resolved on first use and cached; a library with no resolver
 * registered yet answers 0 rather than faulting, which is the same thing a placeholder
 * would have done, and the report below says which it was. */
static void *(*aot_gles_resolver)(const char *name);
void husk_shim_set_gles_resolver(void *fn)
{
    aot_gles_resolver = (void *(*)(const char *))fn;
}
static void *aot_forward_gl(const char *name)
{
    static __thread const char *complained;
    if (!aot_gles_resolver) {
        if (complained != name) {
            complained = name;
            husk_shim_logf("bionic-shim: %s has no OpenGL ES resolver yet\\n", name);
        }
        return NULL;
    }
    return aot_gles_resolver(name);
}
"""


def is_data_symbol(name):
    return name in DATA_HINTS


def imports_of(paths):
    out = set()
    for path in paths:
        e = Elf(path)
        symoff, stroff, _ = e.symtab()
        syms = e.symbols()
        for r in e.all_relocs():
            if r["type"] not in (1025, 1026) or not r["sym"]:
                continue
            if r["sym"] >= len(syms) or syms[r["sym"]][4]:
                continue                      # defined here: a self-reference, not an import
            try:
                name = e.sym_name(symoff, stroff, r["sym"])
            except (ValueError, IndexError):
                continue
            # A name that is not printable ASCII did not come from the string table: the
            # offset ran past its end and the scan found a NUL further along. Emitting one
            # of those produces a shim symbol that looks real and is not.
            if not name or not name.isascii() or not name.isprintable():
                continue
            out.add(name)
    return out


def probe(names, target="arm64-apple-macos", driver="clang++", link=()):
    """The subset of `names` the linker cannot resolve against the system libraries.

    One link answers the whole question. The references are emitted in assembly rather
    than C because `extern char exit[]` collides with the system's own declaration and the
    compile fails before the linker ever runs -- which looks, from here, exactly like "the
    system provides everything".

    `link` is the list of libraries the guest itself links against (["-lz"] and the
    like). A name one of them provides must not be given a placeholder here: the guest
    would bind to the placeholder rather than to the library that has the real thing, and
    zlib's inflate would be a function that reports itself and returns nothing.
    """
    if not names:
        return []
    tmp = os.environ.get("TMPDIR", "/tmp")
    src = os.path.join(tmp, "aot-shim-probe.s")
    with open(src, "w") as f:
        f.write(".section __DATA,__probe,regular\n")
        f.write(".p2align 3\n")
        for n in names:
            # ELF names carry no underscore; the Mach-O symbol for C function `foo` is
            # `_foo`, so the reference needs one
            f.write(".quad _" + n + "\n")
    # the same driver the conversion links with, so the answer is the one that matters:
    # linking the shim with a different driver than the target would give duplicate
    # symbols for everything the C++ runtime already has
    cmd = ["xcrun", driver, "-target", target, "-dynamiclib", "-o",
           os.path.join(tmp, "aot-shim-probe.dylib"), src] + list(link)
    # The SDK has to be the target's. Without this the probe links a device build
    # against the host SDK, the link fails for that reason rather than for the missing
    # symbols, and the answer comes back "the system provides everything" -- which is
    # how the device build ended up with a shim that defined nothing and could not be
    # linked against. The conversion asks for the same SDK, so the two agree.
    sdkname = sdk_for_target(target)
    if sdkname:
        sdk = subprocess.run(["xcrun", "--sdk", sdkname, "--show-sdk-path"],
                             capture_output=True, text=True)
        if sdk.returncode == 0 and sdk.stdout.strip():
            cmd += ["-isysroot", sdk.stdout.strip()]
    r = subprocess.run(cmd, capture_output=True, text=True)
    missing = set()
    for line in r.stderr.splitlines():
        m = re.match(r'\s*"([^"]+)", referenced from:', line)
        if m:
            missing.add(m.group(1).lstrip("_"))
    if not missing and r.returncode == 0:
        raise SystemExit("the shim probe linked cleanly, which cannot be right: it should "
                         "name at least the symbols no system library has")
    if not missing and r.returncode != 0:
        # The link failed for some reason other than a missing symbol, so the answer
        # would be a guess. Say so rather than quietly defining nothing.
        raise SystemExit("the shim probe link failed before it could answer:\n"
                         + (r.stderr or r.stdout))
    return sorted(missing)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("libs", nargs="+")
    ap.add_argument("-o", "--out", required=True)
    ap.add_argument("--exclude", action="append", default=[])
    ap.add_argument("--exclude-file", default=None)
    ap.add_argument("--link", action="append", default=[], metavar="-lNAME",
                    help="a library the guest links against, and so one the probe links "
                         "against too: a name it provides must not get a placeholder")
    ap.add_argument("--no-probe", action="store_true",
                    help="do not ask the linker which of these libSystem already provides")
    ap.add_argument("--forward-gl", action="store_true",
                    help="forward gl* to the host's OpenGL ES rather than leave a stub")
    ap.add_argument("--forward-opensles", action="store_true",
                    help="forward sl* to the host's OpenSL ES, and give SL_IID_* real storage")
    ap.add_argument("--forward", action="append", default=[],
                    help="forward this name to the translation layer's own implementation")
    ap.add_argument("--forward-data", action="append", default=[],
                    help="define this imported constant as storage the host fills in")
    ap.add_argument("--target", default="arm64-apple-macos")
    ap.add_argument("--driver", default="clang++",
                    help="the clang driver to ask; match whatever the target links with")
    ap.add_argument("--record", default=None,
                    help="write the import/resolution split here, for the record")
    a = ap.parse_args(argv[1:])

    excluded = set(a.exclude)
    if a.exclude_file and os.path.exists(a.exclude_file):
        excluded |= {ln.strip() for ln in open(a.exclude_file) if ln.strip() and
                     not ln.startswith("#")}

    candidates = sorted(n for n in imports_of(a.libs) if n not in excluded)
    # A name that is forwarded or filled in is defined here, so it must not also be given a
    # placeholder: two definitions of one symbol do not link.
    forward = {n: "host" for n in a.forward}
    if a.forward_gl:
        forward.update({n: "gl" for n in candidates if re.match(r"gl[A-Z]", n)})
    forward_data = {n: "data" for n in a.forward_data}
    if a.forward_opensles:
        # OpenSL ES is bootstrapped through one call: everything else is reached through the
        # engine's interface table, which is why the guest imports slCreateEngine and not a
        # list of operations. The interface ids are constants it passes by address.
        forward.update({n: "host" for n in candidates if re.match(r"sl[A-Z]", n)})
        forward_data.update({n: "data" for n in candidates if n.startswith("SL_IID_")})
    defined = set(forward) | set(forward_data)

    names = [n for n in candidates if n not in defined]
    names = probe(names, a.target, a.driver, a.link) if not a.no_probe else names
    lines = [PROLOGUE, FWD_TYPEDEF]
    if any(v == "gl" for v in forward.values()):
        lines.append(FORWARDER_NOTE)
    data = []
    # Every placeholder carries its Mach-O name in an asm label rather than relying on the
    # ELF name being a valid C identifier: ELF names carry no leading underscore (Mach-O
    # adds one) and may be C++ mangled, so both `_ZN2EA6Nimble6getEnvEv` and `_exit` have
    # to come out verbatim.
    for i, n in enumerate(names):
        # An explicit asm label is used verbatim, so it has to carry the leading
        # underscore a Mach-O symbol gets: the ELF's name is "slCreateEngine", the
        # symbol the guest binds is "_slCreateEngine".
        if is_data_symbol(n):
            lines.append(f"void *aot_data_{i}[3] __asm__(\"_{n}\");")
            data.append(n)
        else:
            # A placeholder is a last resort, not a first one: the translation layer
            # implements a good many of the names the platform does not have, and the
            # guest is better served by the real thing than by a stub that reports
            # itself. So the placeholder asks the layer first, and only says so when
            # there is nothing there.
            #
            # The arguments are the argument registers, all sixteen of them, and they are
            # passed on untouched: the implementation sees exactly what the guest
            # passed, whatever the types are.
            lines.append(f"unsigned long aot_gap_{i}({FWD_PARAMS}) __asm__(\"_{n}\");")
            lines.append(
                f"unsigned long aot_gap_{i}({FWD_PARAMS})\n"
                f"{{\n"
                f"    static {FWD_CAST} impl;\n"
                f"    if (!impl) impl = ({FWD_CAST})husk_shim_host_impl(\"{n}\");\n"
                f"    if (impl) return impl({FWD_ARGS});\n"
                f"    shim_gap(\"{n}\");\n"
                f"    return 0;\n"
                f"}}")
    for i, n in enumerate(sorted(forward)):
        resolve = "aot_forward_gl" if forward[n] == "gl" else "husk_shim_host_impl"
        lines.append(f"unsigned long aot_fwd_{i}({FWD_PARAMS}) __asm__(\"_{n}\");")
        lines.append(
            f"unsigned long aot_fwd_{i}({FWD_PARAMS})\n"
            f"{{\n"
            f"    static {FWD_CAST} impl;\n"
            f"    if (!impl) impl = ({FWD_CAST}){resolve}(\"{n}\");\n"
            f"    return impl ? impl({FWD_ARGS}) : 0;\n"
            f"}}")
    for i, n in enumerate(sorted(forward_data)):
        # A constant the guest takes the address of: the value is whatever the host made,
        # so this is storage the host fills in through husk_shim_set_data.
        lines.append(f"unsigned long aot_fwd_data_{i} __asm__(\"_{n}\");")
    lines.append(EPILOGUE)
    open(a.out, "w").write("\n".join(lines))
    print(f"{a.out}: {len(names) - len(data)} function placeholders, {len(data)} data "
          f"symbols, {len(forward)} forwarders, {len(forward_data)} host-filled "
          f"constants, out of {len(candidates)} imports "
          f"({len(candidates) - len(names) - len(defined)} already provided by the system)")
    if a.record:
        with open(a.record, "w") as f:
            json.dump({"imports": candidates, "shim_defines": names,
                       "forwarded": {n: forward[n] for n in sorted(forward)},
                       "host_filled": sorted(forward_data),
                       "system_provides": sorted(set(candidates) - set(names) - defined)},
                      f, indent=1)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))